"use strict";
const assert = require("node:assert/strict");
const { validateDocument, listDocuments, validateStationery, stationeryForPage } = require("./lib/document-register.cjs");
const base = { organizationId: "firma-a", projectId: "graun", date: "2026-10-14", type: "Bestellung", reference: "Graun Rekumer Straße 68", description: "Eurofast Befestigungsmaterial", fileId: "pdf-1", createdBy: "user-a" };
const docA = validateDocument({ ...base, id: "best-1" });
const docB = validateDocument({ ...base, id: "best-2", date: "2026-10-13", type: "Brief" });
const foreign = validateDocument({ ...base, id: "foreign", organizationId: "firma-b" });
assert.deepEqual(listDocuments([docB, foreign, docA], { organizationId: "firma-a" }).map(x => x.id), ["best-1", "best-2"]);
assert.deepEqual(listDocuments([docB, foreign, docA], { organizationId: "firma-a", search: "Eurofast", type: "Bestellung" }).map(x=>x.id), ["best-1"]);
assert.deepEqual(listDocuments([docA], { organizationId: "firma-a", projectId: "anderes-projekt" }), []);
assert.throws(() => listDocuments([docA], {}), /Mandant/);
assert.throws(() => validateDocument({ ...base, id: "bad", fileId: "" }), /Datei/);
assert.throws(() => validateDocument({ ...base, id: "bad", date: "14.10.2026" }), /Datum/);
const paper = validateStationery({ organizationId: "firma-a", userId: "user-a", firstPageFileId: "erst", followingPageFileId: "folge" });
assert.equal(stationeryForPage(paper, 1), "erst");
assert.equal(stationeryForPage(paper, 2), "folge");
assert.equal(stationeryForPage(validateStationery({ organizationId: "firma-a", userId: "user-a", firstPageFileId: "erst" }), 3), "erst");
assert.throws(() => stationeryForPage(paper, 0), /Seitennummer/);
console.log("Module 37/38: Fachmodelltests erfolgreich");
