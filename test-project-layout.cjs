const fs = require('node:fs');
const assert = require('node:assert/strict');
const { JSDOM } = require(process.env.DWP_TEST_JSDOM || 'jsdom');
const dom = new JSDOM(fs.readFileSync('index.html', 'utf8'), { url: 'https://dachwerk.test', runScripts: 'outside-only' });
const w = dom.window;
w.scrollTo = () => {};
w.confirm = () => true;
w.eval(fs.readFileSync('app.js', 'utf8'));
w.eval("renderView('projects')");
const query = s => w.document.querySelector(s);
const rows = () => [...w.document.querySelectorAll('[data-project-list] tbody tr')];
assert.equal(w.document.querySelectorAll('.project-card').length, 8);
query('[data-action="list-view"]').click();
assert.equal(rows().length, 8);
assert.equal(query('.project-board').style.display, 'none');
assert.equal(query('[data-action="list-view"]').textContent, 'Kartenansicht');
const filter = query('.project-filter');
filter.value = 'Bremen';
filter.dispatchEvent(new w.Event('input'));
assert.equal(rows().filter(r => r.style.display !== 'none').length, 3);
query('[data-action="list-view"]').click();
assert.equal(query('[data-project-list]'), null);
assert.equal(query('.project-board').style.display, '');
query('[data-action="list-view"]').click();
w.eval("renderView('dashboard');renderView('projects')");
assert.equal(rows().length, 8);
assert.equal(w.localStorage.getItem('dwp-project-layout'), 'list');
assert.equal(w.document.querySelectorAll('[data-project-list]').length, 1);
dom.window.close();
console.log('Project layout: cards, list, filter and persisted preference passed.');
