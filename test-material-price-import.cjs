const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {JSDOM}=require('jsdom'),ExcelJS=require('exceljs'),fflate=require('fflate');
const core=require('./project-core.js'),prices=require('./material-price-import.js'),excel=require('./spreadsheet-import.js');
const {execute,memoryRepository}=require('./lib/project-service.cjs');
(async()=>{
  const repository=memoryRepository(),actor={id:'admin',name:'Prüfer',tenantId:'test',role:'admin'};
  let revision=0;
  const run=async(method,args)=>{const result=await execute(repository,actor,{method,args,revision});revision=result.state.revision;return result.state.records.find(r=>r.id===result.recordId) || result.state.records.flatMap(r=>r.quotes || []).find(q=>q.id===result.recordId);};
  // Server command path and reload: packaged price, discount and freight are normalized once.
  const material=await run('save',['materials',{name:'Bahn',article:'00123',unit:'m²',price:10,priceDate:'2026-01-01',source:'Alt'}]);
  const supplier=await run('save',['suppliers',{name:'Händler A'}]);
  const quote=await run('quote',[supplier.id,{materialId:material.id,price:'120',discount:'10',freight:'12',baseQuantity:'10',packageUnit:'Rolle',date:'2026-01-01',validUntil:'2099-12-31',source:'Angebot 123'}]);
  assert.equal(quote.baseQuantity,10);
  const state=await repository.read(actor.tenantId);
  let store=new core.Store({getItem:()=>JSON.stringify(state.state),setItem:()=>{}});
  assert.equal(store.quotes(material.id)[0].effectivePrice,12);
  await run('useQuote',[supplier.id,quote.id]);
  const latest=await repository.read(actor.tenantId);
  store=new core.Store({getItem:()=>JSON.stringify(latest.state),setItem:()=>{}});
  assert.equal(store.get(material.id).data.price,12);assert.equal(store.get(material.id).data.validUntil,'2099-12-31');
  assert.match(store.get(material.id).data.priceBasis,/10 m²/);
  assert.equal(store.get(material.id).history.at(-1).price,10);
  await run('importMaterials',[[{name:'Bahn',article:'00123',unit:'m²',price:13,supplier:'Händler A'}],{source:'Neu.csv',priceDate:'2026-02-01'}]);
  const importedState=(await repository.read(actor.tenantId)).state;
  assert.equal(importedState.records.find(r=>r.id===material.id).data.price,12);
  assert.equal(importedState.records.find(r=>r.id===material.id).pendingPrice.data.price,13);
  await assert.rejects(run('quote',[supplier.id,{materialId:material.id,price:1,baseQuantity:0,date:'2026-01-01',source:'X'}]),/Gebindeinhalt/);
  const expired=await run('quote',[supplier.id,{materialId:material.id,price:1,date:'2020-01-01',validUntil:'2020-01-02',source:'Alt'}]);
  await assert.rejects(run('useQuote',[supplier.id,expired.id]),/abgelaufen/);
  const corrupt=JSON.parse(store.backup());corrupt.records.find(r=>r.id===supplier.id).quotes[0].baseQuantity=0;
  assert.throws(()=>store.restore(JSON.stringify(corrupt)),/Gebinde/);
  // Legacy quotes retain their unit price with implicit baseQuantity=1.
  const legacy=JSON.parse(store.backup());delete legacy.records.find(r=>r.id===supplier.id).quotes[0].baseQuantity;
  const legacyStore=new core.Store({getItem:()=>JSON.stringify(legacy),setItem:()=>{}});
  assert.equal(legacyStore.quotes(material.id)[0].effectivePrice,120);
  const csv='Artikelnummer;Bezeichnung;Einheit;Listenpreis;Rabatt;Fracht;Gebindeinhalt\r\n00123;"Bahn; grün";m²;120,00;10;12;10';
  const book=prices.csv(csv),mapping=prices.suggest(book.sheets[0].rows[0].values);
  assert.equal(mapping.article,0);assert.equal(mapping.price,3);
  const report=prices.report(book,0,1,mapping,core);
  assert.equal(report.rows[0].article,'00123');assert.equal(report.rows[0].price,12);assert.equal(report.rows[0].name,'Bahn; grün');
  assert.throws(()=>prices.csv('name;unit;price\n"broken;m²;3'),/nicht geschlossen/);
  assert.throws(()=>prices.csv('name;unit;price\nBahn;m²;3;extra'),/Spaltenzahlen/);
  assert.throws(()=>prices.report(book,0,1,{...mapping,price:1},core),/nur einem/);
  assert.equal(prices.suggest([{value:'EK'},{value:'Listenpreis'}]).price,-1,'Mehrdeutige Preisspalten benötigen Auswahl');
  const workbook=new ExcelJS.Workbook(),sheet=workbook.addWorksheet('Preisblatt');
  sheet.addRow(['Hinweiszeile']);sheet.addRow(['Artikelnr.','Bezeichnung','Einheit','Nettopreis','Gebindeinhalt']);
  sheet.addRow([123,'Bahn','m²',120,10]);sheet.getCell('A3').numFmt='00000';
  sheet.addRow(['00200','Formelartikel','m²',{formula:'60*2',result:120},10]);
  sheet.addRow(['00300','Versteckt','m²',50,5]);sheet.getRow(5).hidden=true;
  const bytes=await workbook.xlsx.writeBuffer();
  const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://dachwerk.test',runScripts:'outside-only'}),w=dom.window;
  const parsed=excel.parse(bytes,{unzip:fflate.unzipSync,Parser:w.DOMParser});
  const mapped=prices.suggest(parsed.sheets[0].rows[1].values),checked=prices.report(parsed,0,2,mapped,core);
  assert.equal(checked.rows[0].article,'00123');assert.equal(checked.rows[0].price,12);assert.equal(checked.findings.length,2);
  assert.match(checked.findings[0].reason,/Formel/);assert.match(checked.findings[1].reason,/Ausgeblendet/);
  // The real UI requires a fresh validated preview, commits all rows or none and preserves approved prices.
  w.localStorage.setItem('dwp-project-core-v1',store.backup());w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};w.confirm=()=>true;
  w.TextDecoder=TextDecoder;w.fflate=fflate;
  for(const file of ['app.js','module-fixes.js','project-core.js','module-verification.js','spreadsheet-import.js','material-price-import.js','project-workflows.js'])vm.runInContext(fs.readFileSync(file,'utf8'),dom.getInternalVMContext(),{filename:file});
  w.DWPWorkspace.open('pricelists');
  const form=w.document.querySelector('#dwp-price-import'),click=action=>w.document.querySelector(`[data-dwp="${action}"]`).click();
  const submit=()=>form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  form.elements.source.value='Liste.csv';form.elements.priceDate.value='2026-01-01';
  form.elements.csv.value=csv;click('price-csv');
  let saved=()=>JSON.parse(w.localStorage.getItem('dwp-project-core-v1'));
  const before=saved().revision;submit();assert.equal(saved().revision,before,'Keine Übernahme ohne Vorschau');
  click('price-preview');assert.match(w.document.querySelector('#dwp-price-preview').textContent,/12,00/);
  form.elements.source.value='Neue Liste.csv';submit();assert.equal(saved().revision,before,'Geänderte Quelle benötigt neue Vorschau');
  click('price-preview');submit();assert.equal(saved().revision,before+1);
  assert.equal(saved().records.filter(r=>r.module==='pricelists').length,1);
  assert.equal(saved().records.find(r=>r.module==='materials'&&r.data.name==='Bahn; grün').status,'Prüfung');
  assert.match(saved().records.find(r=>r.module==='materials'&&r.data.name==='Bahn; grün').data.priceBasis,/120 EUR/);
  // Exercise asynchronous XLSX drag/drop, including stale out-of-order completion.
  w.DWPWorkspace.open('pricelists');
  let resolveOld;
  const drop=file=>{const event=new w.Event('drop',{bubbles:true,cancelable:true});Object.defineProperty(event,'dataTransfer',{value:{files:[file]}});w.document.querySelector('#dwp-price-drop').dispatchEvent(event);};
  drop({name:'Alt.xlsx',size:bytes.length,arrayBuffer:()=>new Promise(resolve=>{resolveOld=resolve;})});
  drop({name:'Aktuell.xlsx',size:bytes.length,arrayBuffer:async()=>bytes});
  await new Promise(resolve=>setImmediate(resolve));
  assert.equal(w.document.querySelector('#dwp-price-import').elements.source.value,'Aktuell.xlsx');
  resolveOld(bytes);await new Promise(resolve=>setImmediate(resolve));
  assert.equal(w.document.querySelector('#dwp-price-import').elements.source.value,'Aktuell.xlsx');
  const header=w.document.querySelector('#dwp-price-header');header.value='2';header.dispatchEvent(new w.Event('change',{bubbles:true}));
  const failedRevision=saved().revision;click('price-preview');
  assert.match(w.document.querySelector('#dwp-error').textContent,/Formel/);
  w.document.querySelector('#dwp-price-import').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  assert.equal(saved().revision,failedRevision,'Fehlerhafte Excel-Zeilen sperren die ganze Übernahme');
  const clean=new ExcelJS.Workbook(),cleanSheet=clean.addWorksheet('Freigabe');
  cleanSheet.addRow(['Bezeichnung','Einheit','Preis','Gebindeinhalt']);cleanSheet.addRow(['Rolle','m²',120,10]);
  const cleanBytes=await clean.xlsx.writeBuffer();
  drop({name:'Sauber.xlsx',size:cleanBytes.length,arrayBuffer:async()=>cleanBytes});await new Promise(resolve=>setImmediate(resolve));
  click('price-preview');
  assert.match(w.document.querySelector('#dwp-price-preview').textContent,/12,00/);
  w.document.querySelector('#dwp-price-import').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  assert.equal(saved().revision,failedRevision+1);
  assert.equal(saved().records.find(r=>r.module==='materials'&&r.data.name==='Rolle').data.price,12);
  w.DWPWorkspace.open('suppliers');assert(w.document.querySelector('[name="baseQuantity"]'));
  assert.match(w.document.querySelector('#main-content').textContent,/Rolle = 10 m²/);
  dom.window.close();
  console.log('Supplier package conversion, dates, legacy restore, server persistence, CSV/XLSX mapping and guarded UI preview passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
