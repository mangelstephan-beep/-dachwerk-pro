const assert=require('node:assert/strict');
const {Store}=require('./project-core.js');
let raw=null;const db=new Store({getItem:()=>raw,setItem:(_k,v)=>raw=v});
const ok={status:'Freigegeben',owner:'Prüfer'};
db.settings({wage:0,agk:0,profit:0,tax:19});
const c=db.save('customers',{name:'AG'});db.save('projects',{name:'Dach',customerId:c.id,phase:'Erfassung'});
const p=db.save('lv',{number:'010',text:'Bahn',qty:100,unit:'m²',material:10},ok);
const offer=db.issue('offers');db.save('orders',{title:'Hauptauftrag',offerId:offer.id,date:'2026-10-12'},ok);
db.save('measurements',{title:'Dach',positionId:p.id,length:10,width:10,factor:1,date:'2026-10-12'},ok);
const a=db.issue('invoices',{invoiceType:'Abschlagsrechnung',percentage:30});
assert.equal(a.data.net,300);assert.equal(a.data.gross,357);
const b=db.issue('invoices',{invoiceType:'Teilrechnung',percentage:60});
assert.equal(b.data.net,300);assert.equal(b.data.positions[0].previousQty,30);
assert.throws(()=>db.issue('invoices',{invoiceType:'Teilrechnung',percentage:20}),/unter bereits/);
const change=db.save('lv',{number:'N01',text:'Zusatzdetail',kind:'Nachtrag',qty:5,unit:'Stk',material:20},ok);
const changeOffer=db.issue('offers',{offerType:'Nachtragsangebot',baseOfferId:offer.id});
assert.equal(changeOffer.data.net,100);assert.equal(changeOffer.data.baseOfferId,offer.id);
db.save('orders',{title:'Nachtragsauftrag',offerId:changeOffer.id,date:'2026-10-12'},ok);
db.save('measurements',{title:'Detail',positionId:change.id,length:5,width:1,factor:1,date:'2026-10-12'},ok);
const final=db.issue('invoices');assert.equal(final.data.net,500);assert.equal(final.data.gross,595);
assert.equal(db.controlling().revenue,1100);assert.equal(db.controlling().gross,1309);
assert.throws(()=>db.issue('invoices'),/bereits abgerechnet/);
db.save('payments',{title:'Zahlung',invoiceId:a.id,amount:357,date:'2026-10-12'},ok);
const storno=db.stornoInvoice(final.id,{reason:'Abrechnung korrigieren'});
assert.equal(storno.data.net,-500);assert.equal(storno.data.originalNumber,final.data.number);
assert.throws(()=>db.stornoInvoice(final.id,{reason:'Nochmal'}),/bereits storniert/);
const corrected=db.issue('invoices');assert.equal(corrected.data.net,500);
assert.equal(db.controlling().revenue,1100);
const cancelledAdvance=db.stornoInvoice(a.id,{reason:'Zahlung rückerstatten'});
assert.throws(()=>db.save('payments',{title:'Zahlung',invoiceId:a.id,amount:1,date:'2026-10-12'},ok),/stornierte/);
assert.throws(()=>db.save('payments',{title:'Rückzahlung',direction:'Rückzahlung',invoiceId:cancelledAdvance.id,amount:358,date:'2026-10-12'},ok),/Guthaben/);
db.save('payments',{title:'Rückzahlung',direction:'Rückzahlung',invoiceId:cancelledAdvance.id,amount:357,date:'2026-10-12'},ok);
assert.equal(db.controlling().paid,0);
assert.equal(db.get(final.id).data.net,500,'Original invoice remains unchanged');
console.log('Billing: cumulative advance/partial/final quantities, authorized changes, no double billing, storno/reissue, payment/refund bounds and immutable originals passed.');
