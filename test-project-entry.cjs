const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),{JSDOM}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://dachwerk.test',runScripts:'outside-only'}),w=dom.window;
let revealed=null;w.scrollTo=()=>{};w.confirm=()=>true;w.HTMLElement.prototype.scrollIntoView=function(){revealed=this;};
for(const file of ['app.js','module-fixes.js','project-core.js','module-verification.js','project-workflows.js'])vm.runInContext(fs.readFileSync(file,'utf8'),dom.getInternalVMContext(),{filename:file});
const q=s=>w.document.querySelector('#main-content').querySelector(s);
const click=id=>q(`[data-dwp="open"][data-id="${id}"]`).click();
w.DWPRemote={active:true,trackModule:async()=>{}};
w.DWPWorkspace.open('dashboard');
assert(q('#dwp-project').disabled);
assert.match(q('#dwp-project').textContent,/Noch kein Projekt vorhanden/);
for(const id of ['customers','projects'])assert.equal(q(`[data-dwp="open"][data-id="${id}"]`).getAttribute('data-dwp-verified'),null);
click('customers');
assert.equal(q('#dwp-record [name="module"]').value,'customers');
assert.equal(revealed,q('#dwp-record'));
assert.equal(w.document.activeElement,q('#dwp-record'),'Form gets focus without focusing an input and raising the keyboard');
const customer=w.DWPWorkspace.store.save('customers',{name:'Testkunde'});
const project=w.DWPWorkspace.store.save('projects',{name:'Testdach',customerId:customer.id,phase:'Erfassung'});
click('projects');
assert.equal(q('#dwp-record [name="module"]').value,'projects');
assert.equal(revealed,q('#dwp-record'));
assert.equal(q('#dwp-project').disabled,false);
assert(q(`#dwp-project option[value="${project.id}"]`));
w.DWPWorkspace.store.data.selectedProject=null;
w.DWPWorkspace.open('dashboard');
assert.match(q('.dwp-project-context').textContent,/vorhandenes Projekt auswählen/);
assert.doesNotMatch(q('.dwp-project-context').textContent,/anlegen/);
assert(q('[data-dwp="server-reload"]'),'Reload is available beside the project selector');
const second=w.DWPWorkspace.store.save('projects',{name:'Zweites Dach',customerId:customer.id,phase:'Erfassung'});
w.DWPWorkspace.open('dashboard');
q('#dwp-project').value=project.id;q('#dwp-project').dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(w.DWPWorkspace.store.project().id,project.id);
assert.equal(q('#dwp-project').value,project.id);
assert.notEqual(w.DWPWorkspace.store.project().id,second.id);
assert.equal(w.document.querySelector('[data-view="projects"] .nav-count').textContent,'2','Navigation counts server/workspace projects instead of demo data');
const server=JSON.parse(JSON.stringify(w.DWPWorkspace.store.data));server.selectedProject=null;
w.DWPWorkspace.acceptServerState(server,{id:'owner',name:'Owner'});
w.DWPWorkspace.open('dashboard');
q('#dwp-project').value=project.id;q('#dwp-project').dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(w.sessionStorage.getItem('dwp-selected-project:owner'),project.id);
w.DWPWorkspace.store.data.selectedProject=null;
w.DWPWorkspace.acceptServerState(server,{id:'owner',name:'Owner'});
assert.equal(w.DWPWorkspace.store.project().id,project.id,'Confirmed server hydration restores the selection after page reload');
w.DWPWorkspace.acceptServerState(server,{id:'other',name:'Other'});
assert.equal(w.DWPWorkspace.store.project(),undefined,'Selections do not cross user accounts');
w.DWPWorkspace.acceptServerState({...server,records:server.records.filter(r=>r.id!==project.id)},{id:'owner',name:'Owner'});
assert.equal(w.DWPWorkspace.store.project(),undefined,'Removed or inaccessible projects are not restored');
assert.equal(w.sessionStorage.getItem('dwp-selected-project:owner'),null,'An invalid remembered selection is cleared');
vm.runInContext(fs.readFileSync('workflow-assistant.js','utf8'),dom.getInternalVMContext(),{filename:'workflow-assistant.js'});
assert(w.document.querySelector('.topbar-actions [data-voice-btn]'),'Voice control belongs to the topbar');
assert.equal(w.document.querySelector('[data-dwp-voice]').style.position,'','Voice control must not float over content');
assert.equal(w.document.querySelector('[data-voice-btn]').getAttribute('aria-label'),'Sprachhilfe öffnen');
dom.window.close();console.log('Project entry: empty-state feedback, revoked green status, customer/project click routing, form focus and scroll, populated selector and project switching passed.');
