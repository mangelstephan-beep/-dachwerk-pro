const assert=require('node:assert/strict');
const {Store}=require('./project-core.js');
let raw=null;
const storage={getItem:()=>raw,setItem:(_k,v)=>{raw=v;}};
const db=new Store(storage);
const approved={status:'Freigegeben',owner:'Prüfer'};
const customer=db.save('customers',{name:'Testkunde'});
const p1=db.save('projects',{name:'Dach A',customerId:customer.id,phase:'Erfassung'});
const material=db.save('materials',{name:'Bahn',unit:'m²',price:10,priceDate:'2026-10-12',source:'Liste'},approved);
db.save('lv',{number:'010',text:'Abdichtung',qty:100,unit:'m²',materialId:material.id,consumption:1.1},approved);
assert.equal(db.materialDemand()[0].quantity,110);
const draft=db.createPurchase(material.id);
assert.equal(draft.data.quantity,110);
assert.throws(()=>db.createPurchase(material.id),/offene Bestellung/);
assert.throws(()=>db.save('logistics',{title:'Lieferung',purchaseId:draft.id,deliveryDate:'2026-10-15',quantity:10},approved),/Bestellung/);
const order=db.save('purchase',draft.data,{...approved,id:draft.id});
db.save('logistics',{title:'Teillieferung',purchaseId:order.id,deliveryDate:'2026-10-15',quantity:60},approved);
assert.equal(db.materialDemand()[0].remaining,0);
assert.equal(db.materialDemand()[0].delivered,60);
assert.throws(()=>db.save('logistics',{title:'Überlieferung',purchaseId:order.id,deliveryDate:'2026-10-16',quantity:51},approved),/offene Bestellmenge/);
db.save('logistics',{title:'Restlieferung',purchaseId:order.id,deliveryDate:'2026-10-16',quantity:50},approved);
assert.equal(db.materialDemand()[0].delivered,110);
assert.throws(()=>db.createPurchase(material.id),/Kein offener/);
const s1=db.save('suppliers',{name:'Händler A'}),s2=db.save('suppliers',{name:'Händler B'});
db.quote(s1.id,{materialId:material.id,price:12,discount:20,freight:0.3,date:'2026-10-12',source:'Angebot A'});
const q=db.quote(s2.id,{materialId:material.id,price:10,discount:10,freight:0.2,date:'2026-10-12',source:'Angebot B'});
assert.equal(db.quotes(material.id)[0].supplierId,s2.id);
assert.equal(db.quotes(material.id)[0].effectivePrice,9.2);
db.useQuote(s2.id,q.id,'Prüfer');
assert.equal(db.get(material.id).data.price,9.2);
assert.equal(db.get(material.id).history[0].price,10);
assert.equal(db.get(order.id).data.unitPrice,10);
db.save('suppliers',{...s2.data,phone:'123'},{id:s2.id});
assert.equal(db.quotes(material.id).length,2,'Editing supplier preserves quotes');
const employee=db.save('personnel',{name:'Mitarbeiter A',number:'P1',employment:'Arbeiter'});
const assignment=db.schedule(employee.id,{projectId:p1.id,start:'2026-10-15',end:'2026-10-17',task:'Abdichtung'});
const p2=db.save('projects',{name:'Dach B',customerId:customer.id,phase:'Erfassung'});
assert.throws(()=>db.schedule(employee.id,{projectId:p2.id,start:'2026-10-17',end:'2026-10-18'}),/bereits eingeplant/);
db.schedule(employee.id,{projectId:p2.id,start:'2026-10-18',end:'2026-10-19'});
db.cancelSchedule(employee.id,assignment.id);
db.schedule(employee.id,{projectId:p2.id,start:'2026-10-15',end:'2026-10-17'});
db.save('personnel',{...employee.data,qualification:'Prüfung'},{id:employee.id});
assert.equal(db.get(employee.id).assignments.length,3,'Editing staff preserves assignments');
db.select(p1.id);
const acceptance=db.save('acceptance',{title:'Abnahme Dach A',date:'2026-10-17',participants:'AG / AN',result:'Mit Restpunkten',remaining:'Detail prüfen'});
const strokes=[[[0.1,0.2],[0.3,0.4],[0.6,0.2]]];
assert.throws(()=>db.sign(acceptance.id,{signer:'Test',strokes:[]}),/unterschreiben/);
assert.throws(()=>db.sign(acceptance.id,{signer:'Test',strokes:[[[2,0],[0,0]]]}),/ungültig/);
db.sign(acceptance.id,{signer:'Test AG',role:'Auftraggeber',strokes});
assert.equal(db.get(acceptance.id).signatures[0].snapshot.data.remaining,'Detail prüfen');
assert.throws(()=>db.save('acceptance',{...acceptance.data,remaining:'Verändert'},{id:acceptance.id}),/unverändert/);
db.sign(acceptance.id,{signer:'Test AN',role:'Auftragnehmer',strokes});
assert.equal(db.get(acceptance.id).signatures.length,2);
const backup=db.backup();
const invalid=JSON.parse(backup);invalid.records.find(r=>r.id===acceptance.id).data.remaining='Verändert';
assert.throws(()=>db.restore(JSON.stringify(invalid)),/Dokumentstand/);
assert.equal(db.backup(),backup);
db.select(p2.id);
assert.throws(()=>db.sign(acceptance.id,{signer:'Falsches Projekt',strokes}),/aktuellen Projekt/);
assert.equal(new Store(storage).get(acceptance.id).signatures.length,2);
db.select(p1.id);
const beforeImport=db.backup();
assert.throws(()=>db.importMaterials([{name:'OK',unit:'m²',price:5},{name:'Fehler',unit:'m²',price:'oops'}],{source:'Test.csv',priceDate:'2026-10-12'}));
assert.equal(db.backup(),beforeImport);
db.importMaterials([{name:'Bahn',unit:'m²',price:8,supplier:'Händler B'},{name:'Neuer Artikel',unit:'Stk',price:'12,50'}],{source:'Preise.csv',priceDate:'2026-10-12'});
assert.equal(db.get(material.id).data.price,9.2,'Approved price remains active pending review');
assert.equal(db.get(material.id).pendingPrice.data.price,8);
assert.equal(db.list('materials').find(r=>r.data.name==='Neuer Artikel').status,'Prüfung');
db.save('materials',db.get(material.id).pendingPrice.data,{...approved,id:material.id});
assert.equal(db.get(material.id).data.price,8);
assert.equal(db.get(material.id).pendingPrice,undefined);
assert.equal(db.list('pricelists').at(-1).data.source,'Preise.csv');
console.log('Execution: demand → purchase → partial deliveries; price comparison/history; cross-project scheduling/conflicts; signature snapshot/freeze/restore integrity passed.');
