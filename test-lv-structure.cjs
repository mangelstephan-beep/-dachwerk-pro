const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const {JSDOM}=require('jsdom');
const {Store}=require('./project-core.js');
const {execute,memoryRepository}=require('./lib/project-service.cjs');
(async()=>{
  const repo=memoryRepository(),actor={id:'admin',name:'Prüfer',role:'admin',tenantId:'lv-tests'};
  let state=(await repo.read(actor.tenantId)).state,projectId;
  const run=async(method,args)=>{const response=await execute(repo,actor,{method,args,revision:state.revision,projectId});state=response.state;return state.records.find(r=>r.id===response.recordId);};
  await run('settings',[{wage:0,agk:0,profit:0}]);
  const customer=await run('save',['customers',{name:'Muster AG'}]);
  const project=await run('save',['projects',{name:'Muster Dach',customerId:customer.id,phase:'Erfassung'}]);projectId=project.id;
  const ok={status:'Freigegeben'};
  const lv=(number,kind,changeNumber,material,groupPath)=>run('save',['lv',{number,text:'Leistung '+number,qty:2,unit:'m²',kind,changeNumber,material,groupPath},ok]);
  const main=await lv('01.01','Hauptleistung','',10,'01 Dach / 01 Abdichtung');
  const obsolete=await run('issue',['offers']);
  const offer=await run('issue',['offers']);
  assert.equal(offer.data.version,2);
  assert.equal(offer.data.supersedesOfferId,obsolete.id);
  assert.equal(obsolete.data.version,1,'Hauptangebotsoriginal bleibt unverändert');
  await assert.rejects(run('save',['orders',{title:'Veralteter Hauptauftrag',offerId:obsolete.id,date:'2026-10-13'},ok]),/ersetzt/);
  await run('save',['orders',{title:'Hauptauftrag',offerId:offer.id,date:'2026-10-13'},ok]);
  await assert.rejects(run('issue',['offers']),/bereits beauftragt/);
  // Older stored offers can lack supersession metadata; overlapping positions still cannot be ordered.
  const legacyRepo=memoryRepository();
  const legacyState=JSON.parse(JSON.stringify(state));
  delete legacyState.records.find(r=>r.id===offer.id).data.supersedesOfferId;
  await legacyRepo.compareAndSwap(actor.tenantId,0,legacyState,{hash:'legacy-fixture'});
  await assert.rejects(execute(legacyRepo,actor,{method:'save',args:['orders',{title:'Doppelte Altbeauftragung',offerId:obsolete.id,date:'2026-10-13'},ok],revision:legacyState.revision,projectId}),/bereits in einem anderen Auftrag/);
  assert.equal((await legacyRepo.read(actor.tenantId)).state.revision,legacyState.revision,'Abgelehnte Doppelbeauftragung ändert keinen Bestand');
  const n1=await lv('N01.01','Nachtrag','N01',20,'01 Dach / 02 Details');
  const n2=await lv('N02.01','Nachtrag','N02',30,'02 Fassade');
  const revision=state.revision;
  await assert.rejects(run('issue',['offers',{offerType:'Nachtragsangebot',baseOfferId:offer.id}]),/Nachtragsnummer/);
  assert.equal(state.revision,revision);
  const opts={offerType:'Nachtragsangebot',baseOfferId:offer.id,changeNumber:'N01'};
  const first=await run('issue',['offers',opts]);
  assert.deepEqual(first.data.positions.map(p=>p.id),[n1.id]);assert.equal(first.data.net,40);
  const second=await run('issue',['offers',opts]);
  assert.equal(second.data.version,2);assert.equal(second.data.supersedesOfferId,first.id);
  await assert.rejects(run('save',['orders',{title:'Alte Fassung',offerId:first.id,date:'2026-10-13'},ok]),/ersetzt/);
  await run('save',['orders',{title:'Nachtrag 1',offerId:second.id,date:'2026-10-13'},ok]);
  await assert.rejects(run('issue',['offers',opts]),/bereits beauftragt/);
  await assert.rejects(lv('BAD','Hauptleistung','',1,'Dach // Detail'),/Gliederung/);
  assert.equal(state.records.filter(r=>r.module==='lv').length,3);
  for(const position of [main,n1])await run('save',['measurements',{title:'Aufmaß',positionId:position.id,length:2,width:1,factor:1,date:'2026-10-13'},ok]);
  const invoice=await run('issue',['invoices']);
  assert.equal(invoice.data.net,60,'Unbeauftragter N02 wird nicht berechnet');
  assert.equal(invoice.data.positions.find(p=>p.id===main.id).groupPath,'01 Dach / 01 Abdichtung');
  let raw=JSON.stringify(state);const db=new Store({getItem:()=>raw,setItem:(_k,v)=>raw=v});
  assert.equal(db.lvGroups().find(g=>g.path==='01 Dach').net,60);
  assert.equal(db.lvGroups().find(g=>g.path==='01 Dach').positions,2);
  assert.equal(db.get(first.id).data.version,1,'Alte Fassung bleibt unverändert');
  // Hierarchical tree: nested levels, subtotal boundaries, optional positions and snapshots.
  const tree=db.lvTree();
  const dach=tree.find(n=>n.path==='01 Dach');
  assert(dach,'Wurzelgruppe ist vorhanden');
  assert.equal(dach.net,60,'Übergeordnete Summe addiert Kinder nicht doppelt');
  assert.equal(dach.children.length,2,'Titel werden als echte Kinder abgebildet');
  assert.equal(dach.children[0].positions.length,1,'Positionen hängen am letzten Titel');
  assert.equal(dach.children[1].positions[0].kind,'Nachtrag');
  const deep=await lv('09.01','Bedarfsposition','',100,'Gewerk / Los / Titel / Abschnitt / Untertitel');
  const updated=new Store({getItem:()=>JSON.stringify(state),setItem:()=>{}});
  const deepRoot=updated.lvTree().find(n=>n.label==='Gewerk');
  assert.equal(deepRoot.children[0].children[0].children[0].children[0].positions[0].id,deep.id);
  assert.equal(deepRoot.net,0,'Bedarfsposition verändert die Grundsumme nicht');
  const beforeTooDeep=state.revision;
  await assert.rejects(lv('10.01','Hauptleistung','',1,'A / B / C / D / E / F'),/Gliederung/);
  assert.equal(state.revision,beforeTooDeep,'Ungültige sechste Ebene wird atomar abgewiesen');

  const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://dachwerk.test',runScripts:'outside-only'}),w=dom.window;
  w.localStorage.setItem('dwp-project-core-v1',raw);w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};w.confirm=()=>true;
  for(const file of ['app.js','module-fixes.js','project-core.js','module-verification.js','project-workflows.js'])vm.runInContext(fs.readFileSync(file,'utf8'),dom.getInternalVMContext(),{filename:file});
  w.DWPWorkspace.open('lv');assert(w.document.querySelector('[name="groupPath"]'));assert(w.document.querySelector('#main-content').textContent.includes('01 Dach / 02 Details'));
  const lvView=w.document.querySelector('#main-content');
  const root=lvView.querySelector('[data-lv-path="01 Dach"]');
  assert(root,'LV-Titelbaum wird im Workspace gerendert');
  assert.equal(root.dataset.lvLevel,'1');
  assert.equal(root.querySelectorAll(':scope > details > .dwp-lv-branches > .dwp-lv-node').length,2,'Untertitel stehen verschachtelt unter dem Haupttitel');
  assert(root.querySelector('[data-lv-position="PLACEHOLDER"]')===null,'HTML-Baum nutzt Positionskennungen statt eines alten Fixture-Wertes');
  assert(root.textContent.includes('60,00'),'Gruppensumme wird in Euro angezeigt');
  assert(lvView.querySelector('[aria-label="LV-Titelhierarchie"]'),'Hierarchie ist beschriftet');
  assert(!lvView.querySelector('.dwp-module-verified'),'LV wird durch die Baumansicht nicht freigegeben');
  w.DWPWorkspace.open('offers');assert.equal(w.document.querySelectorAll('[name="changeNumber"] option').length,2);assert(w.document.querySelector('#main-content').textContent.includes('Version 2'));
  dom.window.close();
  console.log('LV: zentrale Gliederung, Zwischensummen, getrennte Nachträge, unveränderliche Versionen, gesperrte Altfassungen und Aufmaß/Rechnungsbezug bestanden.');
})().catch(e=>{console.error(e);process.exitCode=1;});
