const assert=require('node:assert/strict');
const {Store}=require('./project-core.js');
let snapshot;
const db=new Store({getItem:()=>snapshot||null,setItem:(_key,value)=>{snapshot=value;}});
const customer=db.save('customers',{name:'HIT-Prüfmandant'});
const project=db.save('projects',{name:'HIT 80008',customerId:customer.id,phase:'Erfassung'});
db.select(project.id);
const input={number:'18.1.1',text:'Sperrschicht',qty:766,unit:'m²',kind:'Hauptleistung',groupPath:'18 Abdichtung / 18.1 Sohle',epPrecision:3,useDetailedMaterials:true,materialName1:'Material',materialPrice1:12,materialCut1:1,minutes:14.4,useEfbRates:true,efbWage:62,materialMarkup:30.6368,laborMarkup:20.96};
const hit=db.save('lv',input,{status:'Prüfung'});
assert.equal(db.position(hit).ep,33.675,'3-stelliger EP aus HIT-Faktoren');
assert.equal(db.position(hit).gp,25795.05,'GP auf zwei Stellen aus dreistelligem EP');
const standard=db.save('lv',{...input,number:'18.1.2',epPrecision:0},{status:'Prüfung'});
assert.equal(db.position(standard).ep,33.68,'Alte 2-stellige Kalkulation unverändert');
const optional=db.save('lv',{...input,number:'18.1.3',kind:'Bedarfsposition'},{status:'Prüfung'});
assert.equal(db.position(optional).ep,33.675);
assert.equal(db.calculation().net,25795.05+25798.88,'Bedarfsposition ohne GP in Nettosumme');
const changed=db.save('lv',{...input,materialPrice1:13},{id:hit.id,status:'Prüfung'});
assert.equal(db.position(changed).ep,34.983,'Materialänderung berechnet 3-stelligen EP neu');
assert.equal(db.get(hit.id).data.epPrecision,3,'EP-Präzision bleibt beim Bearbeiten erhalten');
assert.throws(()=>db.save('lv',{...input,number:'18.1.4',epPrecision:4}),/Nachkommastellen/);
console.log('HIT EP-Präzision: OK');
