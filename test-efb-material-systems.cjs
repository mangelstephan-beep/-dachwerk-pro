const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {Store}=require('./project-core.js');
const {execute,memoryRepository}=require('./lib/project-service.cjs');
const {JSDOM}=require('jsdom');
(async()=>{
  const repo=memoryRepository(),actor={id:'reviewer',name:'Prüfer',role:'admin',tenantId:'efb-materials'};
  let state=(await repo.read(actor.tenantId)).state,projectId;
  const run=async(method,args)=>{const out=await execute(repo,actor,{method,args,revision:state.revision,projectId});state=out.state;return state.records.find(r=>r.id===out.recordId);};
  const model=()=>new Store({getItem:()=>JSON.stringify({...state,selectedProject:projectId}),setItem:()=>{}});
  const approved={status:'Freigegeben'};
  const customer=await run('save',['customers',{name:'EFB Auftraggeber'}]);
  projectId=(await run('save',['projects',{name:'Kalkulationsprüfung',customerId:customer.id,phase:'Erfassung'}])).id;
  await run('settings',[{wage:100,agk:50,profit:50}]);
  const source={number:'7',text:'Flachblech',qty:3,unit:'Stk.',minutes:6,material:12.3,useEfbRates:true,efbWage:54,laborMarkup:0,materialMarkup:35,equipmentMarkup:35,subcontractMarkup:35};
  const position=await run('save',['lv',source,approved]);
  let p=model().position(position);
  assert.equal(p.labor,5.4);assert.equal(p.priceComponents.material,16.61);assert.equal(p.calculatedEp,22.01);assert.equal(p.gp,66.03);
  const allCosts=await run('save',['lv',{...source,number:'8',qty:2,equipment:10,subcontract:20,laborMarkup:35},approved]);
  p=model().position(allCosts);
  assert.deepEqual(p.priceComponents,{labor:7.29,material:16.61,equipment:13.5,subcontract:27});
  assert.equal(p.ep,64.4);assert.equal(p.gp,128.8);
  const target=await run('save',['lv',{...source,number:'9',qty:2,useTargetPrice:true,targetEp:30,discountPercent:10},approved]);
  assert.equal(model().position(target).gp,54);
  const legacy=await run('save',['lv',{number:'L',text:'Bisherige Kalkulation',qty:1,unit:'m',minutes:6,material:12.3},approved]);
  assert.equal(model().position(legacy).ep,50.18);
  const revision=state.revision;
  await assert.rejects(run('save',['lv',{...source,number:'bad',efbWage:0}]),/Kalkulationslohn/);assert.equal(state.revision,revision);
  const offer=await run('issue',['offers']);
  await run('settings',[{wage:60,agk:0,profit:0}]);
  assert.equal(model().get(offer.id).data.positions[0].ep,22.01);
  assert.equal(model().position(position).ep,22.01);
  const materialData={name:'Abdichtungsbahn',article:'00123',manufacturer:'Testhersteller',supplier:'Händler',unit:'m²',price:10,priceDate:'2026-01-01',validUntil:'2099-12-31',source:'Angebot 123',system:'Prüfaufbau',documentUrl:'https://example.org/produkt.pdf',documentEdition:'2026-01',compatibility:'Geeignet laut Nachweis',compatibilityEvidence:'Für den konkreten Aufbau geprüft.'};
  const material=await run('save',['materials',materialData,approved]);
  assert.deepEqual(model().materialChecks(material,'2099-12-31'),[]);
  assert(model().materialChecks(material,'2100-01-01').includes('Preisbindung abgelaufen'));
  assert(model().materialChecks(material,'2025-12-31').includes('Preisstand liegt in der Zukunft'));
  const matPosition=await run('save',['lv',{number:'M',text:'Materialbezug',qty:2,unit:'m²',materialId:material.id,consumption:2},approved]);
  assert.equal(model().position(matPosition).material,20);
  const safeOffer=await run('issue',['offers']);
  await run('save',['materials',{...materialData,validUntil:'2026-01-01'},{...approved,id:material.id}]);
  await assert.rejects(run('issue',['offers']),/Preisbindung abgelaufen/);
  assert(model().contractChecks().some(f=>f.number==='M' && f.finding==='Preisbindung abgelaufen'));
  assert.equal(model().get(safeOffer.id).data.positions.find(p=>p.id===matPosition.id).ep,20);
  await assert.rejects(run('save',['materials',{...materialData,validUntil:'2025-01-01'}]),/Preisbindung/);
  await assert.rejects(run('save',['materials',{...materialData,validUntil:'2026-02-30'}]),/Preisbindung/);
  for(const documentUrl of ['javascript:alert(1)','http://example.org/x','https://user:password@example.org'])await assert.rejects(run('save',['materials',{...materialData,documentUrl}]),/HTTPS/);
  await assert.rejects(run('save',['materials',{...materialData,compatibilityEvidence:''}]),/Eignungsnachweis/);
  await run('save',['materials',{...materialData,compatibility:'Ungeprüft'},{...approved,id:material.id}]);
  await assert.rejects(run('issue',['offers']),/Systemverträglichkeit ungeprüft/);
  await run('save',['materials',{...materialData,compatibility:'Nicht geeignet'},{...approved,id:material.id}]);
  await assert.rejects(run('issue',['offers']),/nicht geeignet/);
  await run('save',['materials',materialData,{...approved,id:material.id}]);
  await run('importMaterials',[[{name:materialData.name,article:materialData.article,manufacturer:materialData.manufacturer,unit:'m²',price:11}],{source:'Neues Angebot',priceDate:'2026-02-01',supplier:'Händler',validUntil:'2099-11-30'}]);
  const pending=model().get(material.id);
  assert.equal(pending.data.price,10);assert.equal(pending.pendingPrice.data.price,11);
  assert.equal(pending.pendingPrice.data.validUntil,'2099-11-30');assert.equal(pending.pendingPrice.data.documentEdition,'2026-01');
  await run('save',['materials',pending.pendingPrice.data,{...approved,id:material.id}]);
  assert.equal(model().get(material.id).data.article,'00123');
  assert.equal(model().get(material.id).history.at(-1).validUntil,'2099-12-31');
  const corrupt=JSON.parse(model().backup());corrupt.records.find(r=>r.id===position.id).data.efbWage=0;
  assert.throws(()=>model().restore(JSON.stringify(corrupt)),/Kalkulationslohn/);
  const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://dachwerk.test',runScripts:'outside-only'}),w=dom.window;
  w.localStorage.setItem('dwp-project-core-v1',model().backup());w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};w.confirm=()=>true;
  for(const file of ['app.js','module-fixes.js','project-core.js','module-verification.js','project-workflows.js'])vm.runInContext(fs.readFileSync(file,'utf8'),dom.getInternalVMContext(),{filename:file});
  w.DWPWorkspace.open('efb');
  assert(w.document.querySelector('#main-content').textContent.includes('22,01'));
  w.document.querySelector(`[data-dwp="edit"][data-id="${position.id}"]`).click();
  assert.equal(w.document.querySelector('#dwp-record [name="efbWage"]').value,'54');
  assert(w.document.querySelector('#dwp-record [name="useEfbRates"]').checked);
  w.DWPWorkspace.open('materials');
  assert(w.document.querySelector('[name="validUntil"]'));
  assert.equal(w.document.querySelector('a[href="https://example.org/produkt.pdf"]').rel,'noopener noreferrer');
  assert(w.document.querySelector('#main-content').textContent.includes('00123'));
  dom.window.close();
  console.log('EFB component prices, NU, totals, target/discount, server persistence, material validity, system evidence, pending import and DOM routes passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
